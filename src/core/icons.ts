/**
 * @file icons.ts
 * @description the icons of the project, as the components use them
 *
 * The icons of a project are svg files in its folder of icons. For the
 * code to use them, the studio keeps a module beside that folder,
 * `icons.ts`, which imports each of them and gives them all, by their name:
 *
 *   import icon_save from "./icons/save.svg";
 *   import icon_arrow_left from "./icons/arrow-left.svg";
 *
 *   const icons = {
 *       save: icon_save,
 *       arrowLeft: icon_arrow_left,
 *   };
 *
 *   export default icons;
 *
 * It is the usual way of an x4 application. The pages that are generated
 * import it, and so does the code the user writes:
 *
 *   new Button( { label: "Save", icon: icons.save } )
 *
 * A component that takes an icon (a property of the kind "icon" in its
 * description) keeps the name of an icon of the project. What it is built
 * with is not that name: on the surface it is the source of the svg, and
 * in the generated code it is `icons.save`. So `describe` (components.ts)
 * gives neither: it gives a reference to the icon, which who builds the
 * component, or writes its code, turns into what it needs.
 *
 * The icons that are known now are kept here, as the components and the
 * styles are: a component only has an icon that exists.
 *
 * (no DOM here: this file runs as is under node, for the tests)
 */

import type { IconInfo } from "./project.ts";

/** an icon of the project, where a prop of a component wants one */
export interface IconRef {
	$icon: string;		// its name
}

/** says a module of icons is the one of the studio: it can be written again */
export const ICONS_MARK = "GENERATED BY x4studio - DO NOT EDIT";

let icons: IconInfo[] = [];

/**
 * Tell which icons the project has: what a component is built with, and
 * the code that is generated for it, follow.
 */

export function setIcons( list: IconInfo[] ): void {
	icons = list;
}

export function getIcons( ): IconInfo[] {
	return icons;
}

/**
 * the icon of the project that has a name; undefined when there is none
 */

export function findIcon( name: unknown ): IconInfo {
	return typeof name === "string" ? icons.find( icon => icon.name === name ) : undefined;
}

export function iconRef( name: string ): IconRef {
	return { $icon: name };
}

export function isIconRef( value: unknown ): value is IconRef {
	return typeof value === "object" && value !== null && typeof ( value as IconRef ).$icon === "string";
}

/**
 * How an icon is called in the module of the icons: "arrow-left" is
 * `icons.arrowLeft`.
 */

export function iconKey( name: string ): string {
	return name.replace( /-+([a-z0-9])/g, ( _, letter: string ) => letter.toUpperCase( ) ).replace( /-/g, "" );
}

/**
 * What the file of an icon is imported as, in the module of the icons:
 * "arrow-left" gives "icon_arrow_left". A name of its own, which is never
 * a word of the language ("delete", "new").
 */

function iconIdentifier( name: string ): string {
	return `icon_${name.replace( /[^A-Za-z0-9_]/g, "_" )}`;
}

/**
 * The source of the module of the icons. `folder` is the folder of the
 * icons, as the module imports from it ("./icons").
 */

export function iconsModule( list: IconInfo[], folder: string ): string {
	const sorted = [...list].sort( ( a, b ) => a.name.localeCompare( b.name ) );

	const lines = [
		"/**",
		` * ${ICONS_MARK}`,
		" * The icons of the project: this file is written again each time one is added, renamed or removed.",
		" */",
		"",
		...sorted.map( icon => `import ${iconIdentifier( icon.name )} from ${JSON.stringify( `${folder}/${icon.name}.svg` )};` ),
		"",
		"const icons = {",
		...sorted.map( icon => `\t${iconKey( icon.name )}: ${iconIdentifier( icon.name )},` ),
		"};",
		"",
		"export default icons;",
		"",
	];

	return lines.join( "\n" );
}
